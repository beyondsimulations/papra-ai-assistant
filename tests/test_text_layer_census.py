"""The census instrument is quoted by the runbook, so its classification is tested on real PDFs.

Every fixture here is a PDF generated by the same library the census reads with, so the tests
fail if PyMuPDF's geometry assumptions move under it — the drift that would turn a projected risk
number into a fiction.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import fitz
import pytest

ROOT = Path(__file__).resolve().parent.parent
_spec = importlib.util.spec_from_file_location("text_layer_census",
                                               ROOT / "scripts" / "text_layer_census.py")
census = importlib.util.module_from_spec(_spec)
# Registered before exec: `@dataclass` resolves annotations through sys.modules, so a module
# loaded by path has to be in there while its body runs or the first
# `field(default_factory=...)` blows up.
sys.modules[_spec.name] = census
_spec.loader.exec_module(census)  # type: ignore[union-attr]

LETTERHEAD = "Mustermann GmbH, Musterstrasse 1, 10115 Berlin"
BODY = "Rechnung Nr. VH-2024-778812 fuer die erbrachten Leistungen vom Monat Oktober 2026."


def _pdf(lines: list[tuple[float, str]], pages: int = 1) -> bytes:
    """A real PDF with each (y_pt, text) drawn at that distance from the top of the page."""
    doc = fitz.open()
    for _ in range(pages):
        page = doc.new_page(width=595, height=842)  # A4 in points
        for y, text in lines:
            page.insert_text((56, y), text, fontsize=11)
    payload = doc.tobytes()
    doc.close()
    return payload


def _verdict(payload: bytes, band: float = census.DEFAULT_TOP_BAND_PT) -> census.DocVerdict:
    return census.classify_document("doc-1", "x.pdf", payload, band)


def test_a_letterhead_in_the_band_is_at_risk():
    v = _verdict(_pdf([(34, LETTERHEAD), (400, BODY)]))
    assert v.kind == "digital-at-risk"
    assert v.pages == 1 and v.digital_pages == 1 and v.band_pages == 1


def test_digital_text_below_the_band_costs_nothing():
    v = _verdict(_pdf([(400, BODY)]))
    assert v.kind == "digital-clean"
    assert v.digital_pages == 1 and v.band_pages == 0


def test_a_page_with_no_text_layer_is_scanned():
    v = _verdict(_pdf([], pages=2))
    assert v.kind == "scanned"
    assert v.pages == 2 and v.digital_pages == 0


def test_the_band_height_is_the_dial_it_claims_to_be():
    """A headline whose glyph box spans 47-61 pt is at risk at a 60 pt band and clean at 45 pt.

        This is the measurement's whole sensitivity: the strip was bracketed between 40 and 60
    points, so the operator must be able to widen or narrow the question and see the count move.
    The     baseline sits at 58 pt and the box starts ~11 pt above it, because `clip` intersects
    the glyph box     rather than the baseline — which is what the extractor discards, and why the
    numbers below are     read off the box.
    """
    payload = _pdf([(58, "An die Rechnungsfreiheit"), (400, BODY)])
    assert _verdict(payload, band=60.0).kind == "digital-at-risk"
    assert _verdict(payload, band=45.0).kind == "digital-clean"


def test_one_page_with_a_headline_makes_the_whole_document_at_risk():
    doc = fitz.open()
    first = doc.new_page(width=595, height=842)
    first.insert_text((56, 30), LETTERHEAD, fontsize=11)
    for _ in range(3):
        doc.new_page(width=595, height=842)
    payload = doc.tobytes()
    doc.close()
    v = _verdict(payload)
    assert v.kind == "digital-at-risk" and v.pages == 4 and v.band_pages == 1


def test_a_stray_glyph_is_not_treated_as_a_letterhead():
    """Below MIN_BAND_CHARS the band is noise, not an addressee block."""
    assert census.MIN_BAND_CHARS > 1
    v = _verdict(_pdf([(30, "x"), (400, BODY)]))
    assert v.kind == "digital-clean"


def test_a_file_fitz_will_not_open_is_a_row_not_a_crash():
    v = _verdict(b"%PDF-1.4 this is not a pdf")
    assert v.kind == "error" and v.error is not None


def test_an_empty_payload_is_an_error_rather_than_a_scanned_document():
    """A zero-page document must not be counted as "scanned", which would vote against the risk."""
    v = _verdict(b"")
    assert v.kind == "error"


def test_the_sample_is_deterministic_and_respects_the_cap():
    items = [{"id": str(i), "name": f"d{i}.pdf"} for i in range(100)]
    first = census.take_sample(items, 20)
    assert len(first) == 20
    assert [d["id"] for d in first] == [d["id"] for d in census.take_sample(items, 20)]
    assert len(census.take_sample(items, 500)) == 100


def test_non_pdfs_are_neither_sampled_nor_counted():
    items = [{"id": "1", "name": "a.pdf"}, {"id": "2", "name": "note.txt"},
             {"id": "3", "name": "scan", "mimeType": "application/pdf"}]
    assert [d["id"] for d in census.take_sample(items, 10)] == ["1", "3"]


def test_the_projection_scales_the_interval_to_the_bucket_and_never_invents_a_floor():
    result = census.BucketResult(org_id="org", listed=1000, pdfs=400)
    low, high = result.wilson(hits=0, n=40)
    assert low == 0.0 and high > 0            # zero in the sample is not zero in the corpus
    low, high = result.wilson(hits=20, n=40)
    assert low < 200 < high                   # half of 400 sits inside the interval
    assert result.wilson(0, 0) == (0.0, 0.0)


@pytest.mark.parametrize("doc,expected", [
    ({"name": "a.PDF"}, True),
    ({"name": "a.pdf", "mimeType": "image/png"}, True),
    ({"name": "memo.docx"}, False),
    ({"name": "no-extension", "mimeType": "application/pdf"}, True),
])
def test_pdf_detection_covers_the_shapes_the_listing_actually_returns(doc, expected):
    assert census.is_pdf(doc) is expected
